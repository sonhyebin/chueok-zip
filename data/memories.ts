export type MemoryCategory =
  | "music"
  | "drama"
  | "movie"
  | "game"
  | "device"
  | "internet"
  | "fashion"
  | "food"
  | "meme"
  | "school"
  | "photo";

export type MemoryItem = {
  id: string;
  year: number;
  category: MemoryCategory;

  title: string;
  subtitle?: string;

  targetAgeMin?: number;
  targetAgeMax?: number;

  /** 1~5. 5에 가까울수록 그 연도를 대표하는 강한 추억 */
  memoryStrength: number;

  /** 기억을 자극하는 질문 */
  prompt?: string;

  /**
   * 카드 이미지 경로. 비어 있으면 카테고리별 플레이스홀더가 렌더링된다.
   * 실제 이미지는 public/images/years/<연도>/ 아래에 두고
   * "/images/years/<연도>/<id>.jpg" 형태로 지정한다.
   * 예: image: "/images/years/2005/2005-music-1.jpg"
   */
  image?: string;

  /**
   * 실제 자료(licensed-actual) 이미지에만 설정 — 카드 하단에 "자료: …"로 표시되고 원본으로 링크.
   * recreated / generated-original 이미지에는 넣지 않는다.
   */
  credit?: {
    label: string;
    url?: string;
  };

  /**
   * 카드 안에서 곡을 바로 재생할 때 설정 (주로 music 카드).
   * 연도 대표곡(YEAR_INFO.song)과 동일하게 공식 임베드 플레이어로만 재생한다.
   */
  song?: YearSong;

  /** 발매일 — "YYYY.MM.DD" 표기. 카드 부제 아래에 "○○ 발매"로 표시된다. */
  releaseDate?: string;

  /**
   * 그때 물가 — 카드에 "🏷️ 그때 <then> → 지금 <now>" 가격표 칩으로 표시된다.
   * 시대 격차가 재미 포인트인 카드(먹거리·문방구·교통·요금 등)에 붙인다.
   * now는 생략 가능(그때 가격만 보여줌).
   */
  priceThen?: {
    then: string;
    now?: string;
  };

  /**
   * 제휴 앱 설치 CTA — 카드의 기억과 앱이 직결되는 카드에만 붙인다.
   * 연도별 피드 한 화면에 하나만 보이도록 카드를 고르는 것이 원칙.
   */
  cta?: {
    /** lib/config.ts의 PARTNER_APPS 키 */
    app: PartnerAppId;
    label: string;
    /** 버튼 아래 한 줄 설명 */
    note?: string;
  };

  keywords?: string[];
};

